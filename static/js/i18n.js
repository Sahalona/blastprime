/* 支持的语言列表:新增语言时在此加一行,并在 I18N 表中补词条 */
/* Supported languages: add a line here for a new language and add its entries in the I18N table */
const LANGUAGES = [
  { code: "zh", label: "中文" },
  { code: "en", label: "English" },
];

let I18N_LANG = "zh";

function t(key, vars) {
  const table = I18N[I18N_LANG] || I18N.zh;
  let s = key in table ? table[key] : key in I18N.en ? I18N.en[key] : key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split("{" + k + "}").join(String(vars[k]));
    }
  }
  return s;
}

function setLang(lang) {
  I18N_LANG = lang in I18N ? lang : "zh";
  document.documentElement.lang = I18N_LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    // 只替换首个非空文本节点,保留子元素(如标题内嵌的状态徽章 span)
    // Only replace the first non-empty text node, preserving child elements (e.g. status badge spans inside titles)
    let done = false;
    for (const n of el.childNodes) {
      if (n.nodeType === Node.TEXT_NODE) { n.textContent = t(el.dataset.i18n); done = true; break; }
    }
    if (!done) el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  // 导航链接使用 data-nav(renderNav 初始化),切换语言时同步更新
  // Nav links use data-nav (initialized by renderNav); keep them in sync when the language changes
  document.querySelectorAll("[data-nav]").forEach((el) => {
    el.textContent = t("nav." + el.dataset.nav);
  });
  if (window.onLangChanged) window.onLangChanged(I18N_LANG);
}
